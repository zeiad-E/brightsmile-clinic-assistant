/**
 * Rules the code enforces itself — they don't depend on the AI following its prompt.
 */

export const LIMITS = Object.freeze({
  maxMessageChars: 1000,
  maxTurnsPerConversation: 60,
  maxSignInAttempts: 5,
  historyMessages: 10,
  maxReplyChars: 1500,
  maxTokens: 700,
});

/**
 * Emergencies skip the AI entirely: a fixed safety reply goes out instantly and staff are
 * alerted. Kept deliberately narrow (clear danger signs), so ordinary "my tooth hurts"
 * questions still reach the assistant, which escalates them through its own rules.
 */
const EMERGENCY_PATTERNS = [
  /can'?t\s+breathe|cannot\s+breathe|trouble\s+breathing|difficulty\s+breathing|choking/i,
  /(heavy|severe|won'?t\s+stop|non[-\s]?stop|uncontrolled)\s+bleeding|bleeding\s+(heavily|a\s+lot|won'?t\s+stop|for\s+hours)/i,
  /(face|jaw|neck|eye|throat)\s+(is\s+)?(very\s+|badly\s+)?swell|swelling\s+(in|of|on)\s+(my\s+)?(face|jaw|neck|eye|throat)/i,
  /broken\s+jaw|knocked\s+out\s+(a\s+)?tooth|tooth\s+(got\s+)?knocked\s+out|car\s+accident|unconscious|passed\s+out|fainted/i,
  /high\s+fever.*(swell|pain)|(swell|pain).*high\s+fever/i,
  /مش\s*قادر\s*(أ|ا)تنفس|لا\s*(أ|ا)ستطيع\s*التنفس|صعوبة\s*(في\s*)?التنفس|بتخنق|اختناق/,
  /نزيف\s*(شديد|جامد|مش\s*بيقف|لا\s*يتوقف|مستمر)|بينزف\s*(جامد|كتير|ومش\s*بيقف)/,
  /(وشي|وجهي|فكي|رقبتي|عيني)\s*(وارم|ورم|منفوخ|متورم)|تورم\s*(في\s*)?(الوجه|الوش|الفك|الرقبة)/,
  /فقدت\s*الوعي|أغمى\s*علي|اغمى\s*عليا|حادثة|فكي\s*اتكسر|سنة?\s*وقعت\s*من\s*خبطة/,
  /حرارة\s*(عالية|مرتفعة).*(ورم|ألم|وجع)/,
];

export function isEmergency(text) {
  return EMERGENCY_PATTERNS.some((pattern) => pattern.test(text));
}

/**
 * "It's my first visit" vs "I've been here before". The code remembers which one the patient
 * said, so the assistant can't wrongly try to sign a brand-new patient in.
 * Returns true (first visit), false (returning), or null (didn't say).
 */
const RETURNING = /(not\s+(my\s+)?first|been\s+(here|there)\s+before|visited\s+(you\s+|before)|returning\s+patient|have\s+an\s+account|already\s+(a\s+)?patient|مش\s*أول\s*مرة|مش\s*اول\s*مرة|زرتكم\s*قبل|جيت\s*قبل\s*كده|عندي\s*حساب)/i;
const FIRST_VISIT = /(first\s+(time|visit)|new\s+patient|never\s+been|haven'?t\s+been|أول\s*مرة|اول\s*مرة|أول\s*زيارة|اول\s*زيارة|مريض\s*جديد|عمري\s*ما\s*جيت)/i;

export function detectVisitHistory(text) {
  if (RETURNING.test(text)) return false;
  if (FIRST_VISIT.test(text)) return true;
  return null;
}

const ARABIC = /[؀-ۿ]/;
export const detectLanguage = (text, fallback = 'en') => (ARABIC.test(text) ? 'ar' : text.trim() ? 'en' : fallback);

/** Fixed replies the code sends itself (never generated by the AI). */
export function fixedReply(kind, language, extra = {}) {
  const ar = language === 'ar';
  const phone = extra.clinicPhone ?? '';
  switch (kind) {
    case 'emergency':
      return ar
        ? `يبدو أن هذا قد يكون طارئًا. إذا كان هناك صعوبة في التنفس أو نزيف لا يتوقف أو تورم شديد، اتصل بالإسعاف (123) أو توجه لأقرب طوارئ فورًا. أبلغت فريق العيادة وسيتواصلون معك في أسرع وقت${phone ? `، ويمكنك الاتصال بنا على ${phone}` : ''}.`
        : `This may be an emergency. If you have trouble breathing, bleeding that won't stop, or severe swelling, call an ambulance (123) or go to the nearest emergency room now. I've alerted our clinic team and they'll contact you as soon as possible${phone ? `, or call us on ${phone}` : ''}.`;
    case 'off_topic':
      return ar
        ? 'أنا مساعد عيادة برايت سمايل، وأستطيع المساعدة فقط في أمور العيادة: الخدمات والأسعار والمواعيد والحجز والتعديل. كيف أساعدك في ذلك؟ 😊'
        : "I'm BrightSmile's clinic assistant, so I can only help with clinic matters — services, prices, opening hours, and booking or changing appointments. How can I help with those? 😊";
    case 'off_topic_reminder':
      return ar
        ? 'أحب أساعدك، لكن دوري هنا هو أمور العيادة فقط. إذا كنت تريد حجز موعد أو معرفة أسعار خدماتنا فأنا جاهز!'
        : "I'd love to help, but my role here is clinic matters only. If you'd like to book, change an appointment, or ask about our services, I'm ready!";
    case 'injection':
      return ar
        ? 'لا أستطيع تغيير طريقة عملي، لكن يسعدني مساعدتك في أي شيء يخص العيادة.'
        : "I can't change how I work, but I'm happy to help with anything about the clinic.";
    case 'cooldown':
      return ar
        ? 'تم إيقاف المحادثة مؤقتًا. يمكنك المحاولة لاحقًا، أو الاتصال بالعيادة مباشرة.'
        : 'This chat is paused for a little while. Please try again later, or call the clinic directly.';
    case 'turn_limit':
      return ar
        ? 'وصلت هذه المحادثة إلى حدها الأقصى. ابدأ محادثة جديدة وسأكون في خدمتك.'
        : "This conversation has reached its limit. Please start a new chat and I'll be happy to help.";
    case 'paused':
      return ar
        ? `المساعد غير متاح حاليًا. يرجى الاتصال بالعيادة${phone ? ` على ${phone}` : ''}.`
        : `The assistant is unavailable right now. Please call the clinic${phone ? ` on ${phone}` : ''}.`;
    case 'cooldown_start':
      return ar
        ? 'يبدو أن الطلبات خارج نطاق العيادة. سأوقف المحادثة مؤقتًا الآن؛ يمكنك العودة لاحقًا لأي شيء يخص مواعيدك أو خدماتنا.'
        : "It looks like these requests aren't about the clinic, so I'll pause this chat for a little while. Come back any time for anything about your appointments or our services.";
    case 'daily_limit':
      return ar
        ? `وصلت للحد اليومي للمحادثة. يمكنك المتابعة غدًا، أو الاتصال بالعيادة${phone ? ` على ${phone}` : ''}.`
        : `You've reached today's chat limit. You can continue tomorrow, or call the clinic${phone ? ` on ${phone}` : ''}.`;
    case 'unavailable':
      return ar
        ? `المساعد غير متاح مؤقتًا. للحجز يمكنك استخدام الموقع أو الاتصال بالعيادة${phone ? ` على ${phone}` : ''}.`
        : `The assistant is temporarily unavailable. You can book on our website or call the clinic${phone ? ` on ${phone}` : ''}.`;
    case 'failure':
      return ar
        ? 'عذرًا، واجهت مشكلة في إكمال طلبك. أبلغت فريق العيادة وسيتواصلون معك قريبًا.'
        : "Sorry — I ran into a problem completing that. I've passed your conversation to our clinic team and they'll follow up soon.";
    default:
      return '';
  }
}

/** Last check on what the AI wrote, before the patient sees it. */
export function checkReply(reply, language) {
  const text = String(reply ?? '').trim();
  // The prompt marks its rules with this phrase; seeing it in a reply means a leak.
  if (/CLINIC ASSISTANT RULES|BEGIN CONTEXT|END CONTEXT/i.test(text)) return fixedReply('injection', language);
  if (!text) return fixedReply('failure', language);
  return text.length > LIMITS.maxReplyChars ? `${text.slice(0, LIMITS.maxReplyChars - 1)}…` : text;
}
